/**
 * Writes the sentences that say, in plain words, what a finding is.
 *
 *   node build-ruletext.mjs
 *
 * Input:  catalog-src/rule-text.json  { "rule.id": { "en": "...", "ja": "..." } }
 * Output: ../src/Admin/RuleText.php       the English sentences, each inside a
 *                                         translation call so that the usual
 *                                         tools pick them up
 *         ../languages/src/ja-rules.php   their Japanese translations
 *
 * A sentence says what the code does. It names no PHP version and gives no
 * advice: the screen prints both next to it, from the verified data.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const text = JSON.parse(readFileSync(join(here, 'catalog-src', 'rule-text.json'), 'utf8'));
const quote = (value) => "'" + value.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const ids = Object.keys(text).sort();
const problems = [];

for (const id of ids) {
	const { en, ja } = text[id];

	if (!en || !ja) {
		problems.push(`${id}: a sentence is missing`);
	} else if (/%[sd]|%\d+\$[sd]/.test(en) || /%[sd]|%\d+\$[sd]/.test(ja)) {
		problems.push(`${id}: a placeholder; the subject is printed next to the sentence`);
	} else if (/PHP \d\.\d/.test(en)) {
		problems.push(`${id}: names a PHP version; the screen prints the verified one`);
	}
}

if (problems.length > 0) {
	console.error(problems.join('\n'));
	process.exit(1);
}

const php = `<?php
/**
 * What each rule is about, in one plain sentence.
 *
 * GENERATED by tools/build-ruletext.mjs from tools/catalog-src/rule-text.json.
 * Do not edit; change the JSON and run the script.
 *
 * @package UpgradeWarden
 */

namespace TYStudio\\UpgradeWarden\\Admin;

defined( 'ABSPATH' ) || exit;

/**
 * Sentences by rule id. A sentence says what the code does; the PHP versions
 * and what to write instead are printed next to it from the verified data.
 */
final class RuleText {

	/**
	 * The sentence of a rule, or an empty string when there is none.
	 *
	 * @param string $rule Rule id.
	 * @return string
	 */
	public static function sentence( $rule ) {
		$all = self::all();

		return isset( $all[ $rule ] ) ? $all[ $rule ] : '';
	}

	/**
	 * Every sentence, translated.
	 *
	 * @return array<string,string>
	 */
	public static function all() {
		static $all = null;

		if ( null === $all ) {
			$all = array(
${ids.map((id) => `\t\t\t\t${quote(id)} => __( ${quote(text[id].en)}, 'upgrade-warden' ),`).join('\n')}
			);
		}

		return $all;
	}
}
`;

const ja = `<?php
/**
 * Japanese for the sentences of src/Admin/RuleText.php.
 *
 * GENERATED by tools/build-ruletext.mjs from tools/catalog-src/rule-text.json.
 * Do not edit; change the JSON and run the script.
 *
 * @package UpgradeWarden
 */

// phpcs:disable

return array(
${ids.map((id) => `\t${quote(text[id].en)} => ${quote(text[id].ja)},`).join('\n')}
);
`;

mkdirSync(join(here, '..', 'languages', 'src'), { recursive: true });
writeFileSync(join(here, '..', 'src', 'Admin', 'RuleText.php'), php);
writeFileSync(join(here, '..', 'languages', 'src', 'ja-rules.php'), ja);
console.log(`${ids.length} sentences written to src/Admin/RuleText.php and languages/src/ja-rules.php.`);
