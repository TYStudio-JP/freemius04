/**
 * Rule id: argument.null_to_internal_scalar. Deprecated in 8.1.
 *
 *     strlen( null );                  Passing null to parameter #1 ($string) of type string
 *     str_replace( null, '-', $text ); ... of type array|string
 *
 * Only a literal null is reported. The common case, a variable that holds
 * null at run time, cannot be seen in the source (fixture
 * runtime.null_to_internal_scalar_variable). Nor are method calls looked at:
 * the class of the object is not known.
 *
 * Not reported either:
 *
 * - a file with declare( strict_types = 1 ): there null was a TypeError on
 *   every version (fixture runtime.null_to_internal_strict_types);
 * - a function of the same name declared in the file (a namespaced function
 *   that a bare call would reach first);
 * - parameters that accept null, mixed or no scalar type at all (array,
 *   object, callable: those never accepted null).
 *
 * PARAMETERS comes from Reflection on every runtime from 8.1 to 8.5: the
 * parameters whose declared type includes int, float, string or bool and
 * does not allow null on all of them, under the same name and position.
 *
 * The notice is raised when the call runs, so a PHP version check around the
 * call marks the finding as guarded. The fix, offered for parameters of type
 * string only, writes '' instead of null: that is the value PHP before 8.1
 * converted null to, so the program does the same on every version.
 */
