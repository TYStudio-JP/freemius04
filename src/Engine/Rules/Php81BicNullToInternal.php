	/**
	 * {@inheritDoc}
	 */
	public function node_types() {
		return array( Expr\FuncCall::class );
	}

	/**
	 * {@inheritDoc}
	 *
	 * @param Expr\FuncCall $node    Function call.
	 * @param Context       $context Scan state.
	 */
	public function inspect( Node $node, Context $context ) {
		$name = InternalFunctions::global_name( $node->name );

		if ( null === $name || ! isset( self::PARAMETERS[ $name ] ) || isset( $context->declared_functions[ $name ] ) ) {
			return;
		}

		$positional = array();
		$named      = array();

		foreach ( $node->args as $arg ) {
			// A first-class callable (f(...)): no arguments at all.
			if ( ! $arg instanceof Node\Arg ) {
				return;
			}

			// After an unpacked array the positions are unknown.
			if ( $arg->unpack ) {
				break;
			}

			if ( null !== $arg->name ) {
				$named[ strtolower( $arg->name->toString() ) ] = $arg->value;
			} else {
				$positional[] = $arg->value;
			}
		}

		$strict = null;

		foreach ( explode( ' ', self::PARAMETERS[ $name ] ) as $entry ) {
			list( $position, $param, $type ) = explode( ':', $entry, 3 );

			$position = (int) $position;

			if ( isset( $positional[ $position ] ) ) {
				$value = $positional[ $position ];
			} elseif ( isset( $named[ strtolower( $param ) ] ) ) {
				$value = $named[ strtolower( $param ) ];
			} else {
				continue;
			}

			if ( ! $value instanceof Expr\ConstFetch || 'null' !== strtolower( $value->name->toString() ) ) {
				continue;
			}

			if ( null === $strict ) {
				$strict = 1 === preg_match( '/declare\s*\(\s*strict_types\s*=\s*1\s*\)/i', $context->code );
			}

			if ( $strict ) {
				return;
			}

			$finding          = $context->report( 'argument.null_to_internal_scalar', $value, array( 'deprecated' => '8.1' ) );
			$finding->subject = $name . '(): parameter #' . ( $position + 1 ) . ' ($' . $param . ') of type ' . $type;
			$finding->guarded = $context->function_is_guarded( self::VERSION_GUARD );

			if ( 'string' === $type ) {
				$finding->instead = "''";
				$finding->fix     = array(
					'kind'  => 'replace',
					'start' => $value->getStartFilePos(),
					'end'   => $value->getEndFilePos(),
					'text'  => "''",
				);
			} else {
				$finding->instead = 'a value of type ' . $type;
			}
		}
	}
